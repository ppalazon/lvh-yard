// Compose mounts a file that ws init does not write as a folder, and the container then fails to start.
func TestScriptsAreTheFilesThatComposeMounts(t *testing.T) {
	name := "compose.yaml"
	if runtime.GOOS == "windows" {
		name = "compose.windows.yaml"
	}
	source, err := os.ReadFile(name)
	if err != nil {
		t.Fatal(err)
	}
	var file struct {
		Services map[string]struct {
			Volumes []string `yaml:"volumes"`
		} `yaml:"services"`
	}
	if err := yaml.Unmarshal(source, &file); err != nil {
		t.Fatal(err)
	}
	mounted := map[string]bool{}
	for _, service := range file.Services {
		for _, volume := range service.Volumes {
			host, _, _ := strings.Cut(volume, ":")
			if strings.HasSuffix(host, ".sh") {
				mounted[strings.TrimPrefix(host, "./")] = true
			}
		}
	}
	written := map[string]bool{}
	for _, script := range templates.Scripts() {
		written[script.Name] = true
	}
	if !maps.Equal(mounted, written) {
		t.Fatalf("%s mounts %v, but ws init writes %v", name, slices.Sorted(maps.Keys(mounted)), slices.Sorted(maps.Keys(written)))
	}
}

func TestGeneratedNoticeFollowsTheShebang(t *testing.T) {
	for _, script := range templates.Scripts() {
		t.Run(script.Name, func(t *testing.T) {
			if !strings.HasPrefix(script.Text, "#!/bin/sh\n") || strings.Contains(script.Text, "Generated by lvh-yard") {
				t.Fatalf("a script that ws init writes starts with the shebang and has no notice:\n%s", script.Text)
			}
			got := templates.Generated(script.Text)
			rest, found := strings.CutPrefix(got, "#!/bin/sh\n# Generated by lvh-yard.")
			if !found || !strings.HasSuffix(got, "\n"+strings.TrimPrefix(script.Text, "#!/bin/sh\n")) || len(rest) == 0 {
				t.Fatalf("Generated did not put its notice after the shebang:\n%s", got)
			}
		})
	}
}
