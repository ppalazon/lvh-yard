//go:embed lvh-yard.yaml
var dashboard string

// Compose is the compose.yaml of this platform, with the dashboard image pinned to version.
func Compose(version string) (string, error) {
	const image = "ghcr.io/ppalazon/lvh-yard-dashboard:"
	if !strings.Contains(platformCompose, image+"latest}") {
		return "", fmt.Errorf("compose.yaml no longer has the dashboard image that init edits")
	}
	if version == "" || version == "dev" {
		version = "latest"
	}
	return strings.ReplaceAll(platformCompose, image+"latest}", image+version+"}"), nil
}

// Script is a shell script that Compose mounts into a container.
type Script struct {
	// Name is the path of the file in the Workstation Folder.
	Name string
	Text string
}

// Scripts are the scripts that this platform's compose.yaml mounts, as ws init writes them. They are the
// user's to change.
func Scripts() []Script {
	return platformScripts
}

const generatedNotice = "# Generated by lvh-yard. A later lvh-yard command, such as ws compose upgrade, overwrites this file.\n" +
	"# To keep a change, copy this file and point compose.yaml at the copy.\n"

// Generated is a script with a notice that a command wrote it and can overwrite it. Any command other than
// ws init writes a script this way. The notice follows the first line, which is the shebang.
func Generated(script string) string {
	shebang, rest, found := strings.Cut(script, "\n")
	if !found {
		return script
	}
	return shebang + "\n" + generatedNotice + rest
}

